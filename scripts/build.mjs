/**
 * Build both halves of the plugin.
 *
 * The Host half is a normal ESM bundle for Node. The browser half is NOT a
 * normal bundle: the harness loads it through `window.__ModuleLoader__.load`,
 * whose factory receives a `require` bound to the shell's frozen module table
 * (React, `react/jsx-runtime`, `react-dom`, and `@deepseek-ai/dsh-client-ui-*`).
 *
 * So the browser half is bundled as CommonJS with those modules left external,
 * then wrapped in the loader call. Inside that wrapper the factory parameter
 * `require` is exactly what esbuild's emitted `require("react")` resolves to,
 * and the `var module` / `var exports` the banner declares are what esbuild's
 * CJS prologue writes into.
 *
 * @module dsh-token-dashboard/scripts/build
 */
import { build } from 'esbuild'
import { rm, mkdir, readFile, writeFile, cp } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const lib = path.join(root, 'lib')

/** Modules the shell's frozen module table answers, so they stay external. */
const BASELINE_MODULES = [
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
]

const packageJson = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))
const packageName = packageJson.name

await rm(lib, { recursive: true, force: true })
await mkdir(lib, { recursive: true })

// --- Host half -------------------------------------------------------------
await build({
  entryPoints: [path.join(root, 'src/host/index.ts')],
  outfile: path.join(lib, 'index.js'),
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node22',
  sourcemap: false,
  legalComments: 'none',
  // Node builtins and anything the harness provides stay imports; this package
  // ships no runtime dependencies of its own.
  external: ['node:*'],
  packages: 'external',
  banner: { js: '/* dsh-token-dashboard — host half. Generated by scripts/build.mjs. */' },
})

// --- Browser half ----------------------------------------------------------
const clientBanner = [
  '/* dsh-token-dashboard — browser half. Generated by scripts/build.mjs. */',
  'window.__ModuleLoader__.load({',
  `  id: ${JSON.stringify(packageName)},`,
  '  factory: (require) => {',
  '    var module = { exports: {} };',
  '    var exports = module.exports;',
].join('\n')

const clientFooter = [
  '    return module.exports;',
  '  },',
  '});',
].join('\n')

await build({
  entryPoints: [path.join(root, 'src/client/index.tsx')],
  outfile: path.join(lib, 'client.js'),
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  sourcemap: false,
  legalComments: 'none',
  external: BASELINE_MODULES,
  banner: { js: clientBanner },
  footer: { js: clientFooter },
})

// --- Types -----------------------------------------------------------------
// `tsc` is run through Node rather than through `npx` because spawning a
// `.cmd` shim fails with EINVAL on modern Node for Windows.
const { execFile } = await import('node:child_process')
const { promisify } = await import('node:util')
const tscEntry = path.join(root, 'node_modules/typescript/bin/tsc')
if (existsSync(tscEntry)) {
  try {
    await promisify(execFile)(process.execPath, [tscEntry, '-p', 'tsconfig.build.json'], { cwd: root })
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error)
    console.warn(`[build] declaration emit skipped: ${message.split('\n').slice(0, 4).join(' ')}`)
  }
} else {
  console.warn('[build] typescript is not installed; skipping declaration emit')
}

// A package's `types` entry has to exist for editors to resolve the plugin.
const typeEntry = path.join(lib, 'types/index.d.ts')
if (!existsSync(typeEntry)) {
  await mkdir(path.dirname(typeEntry), { recursive: true })
  await writeFile(typeEntry, 'export declare const name: string\nexport declare function apply(ctx: unknown): void\n')
}

// Locale JSON files are not part of the bundle, but shipping them keeps the
// `./locale/*.json` export honest for hosts that read dictionaries from disk.
if (existsSync(path.join(root, 'locale'))) {
  await cp(path.join(root, 'locale'), path.join(lib, 'locale'), { recursive: true })
}

const hostSize = (await import('node:fs')).statSync(path.join(lib, 'index.js')).size
const clientSize = (await import('node:fs')).statSync(path.join(lib, 'client.js')).size
console.log(`[build] lib/index.js  ${(hostSize / 1024).toFixed(1)} KiB`)
console.log(`[build] lib/client.js ${(clientSize / 1024).toFixed(1)} KiB`)
